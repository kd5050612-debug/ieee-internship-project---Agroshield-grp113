export function useTranslation(ns: Namespace) {
  const [currentLanguage, setCurrentLanguage] = useState<Language>(() => {
    if (typeof window !== 'undefined') {
      const saved = localStorage.getItem('agrilens_lang') as Language;
      if (saved && supportedLanguages.some((l) => l.lang === saved)) {
        return saved;
      }
    }
    return 'en';
  });

  useEffect(() => {
    localStorage.setItem('agrilens_lang', currentLanguage);
    
    // Automatically update HTML document direction for RTL support if necessary
    const targetLang = supportedLanguages.find((l) => l.lang === currentLanguage);
    document.documentElement.dir = targetLang?.rtl ? 'rtl' : 'ltr';
    document.documentElement.lang = currentLanguage;
  }, [currentLanguage]);

  const t = useMemo(() => {
    return (key: string, fallback?: string): string => {
      const targetNamespace = translations[currentLanguage]?.[ns];
      if (targetNamespace && key in targetNamespace) {
        return targetNamespace[key];
      }
      // Fallback mechanics to 'en' configuration if key missing in translation target
      const englishFallback = translations['en']?.[ns]?.[key];
      return englishFallback ?? fallback ?? key;
    };
  }, [currentLanguage, ns]);

  return {
    t,
    currentLanguage,
    setLanguage: setCurrentLanguage,
    supportedLanguages,
  };
}